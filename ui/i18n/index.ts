/** Typed by the language set and the key set, so a missing language or message fails to compile. */
export const DICTIONARIES: Readonly<Record<UiLang, Readonly<Record<MsgKey, string>>>> = {
  en, 'zh-CN': zhCN, ja, fr,
}

export function useT(previewLanguage?: UiLang): (key: MsgKey) => string {
  const configuredLanguage = useConfig((s) => s.config?.uiLang)
  const lang = previewLanguage ?? configuredLanguage ?? 'en'
  const dict = DICTIONARIES[lang] ?? en
  return (key) => dict[key] ?? en[key]
}
